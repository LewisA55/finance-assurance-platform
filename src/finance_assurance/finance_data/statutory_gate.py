def validate_statutory_gate() -> None:
    """Fail if the checked-in A2 design authority is not closed."""

    dataset_ids = tuple(item.dataset_id for item in STATUTORY_SOURCE_REGISTRY)
    paths = tuple(item.path for item in STATUTORY_SOURCE_REGISTRY)
    if len(dataset_ids) != len(set(dataset_ids)):
        raise ValueError("A2 dataset IDs are duplicated")
    if len(paths) != len(set(paths)):
        raise ValueError("A2 source paths are duplicated")
    for definition in STATUTORY_SOURCE_REGISTRY:
        if not definition.dataset_id.isascii() or not definition.path.isascii():
            raise ValueError("A2 registry identity is not ASCII")
        if not definition.path.endswith(".csv"):
            raise ValueError("A2 source path is not CSV")
        if len(definition.columns) != len(set(definition.columns)):
            raise ValueError(f"A2 columns are duplicated: {definition.dataset_id}")
        if not definition.columns:
            raise ValueError(f"A2 columns are absent: {definition.dataset_id}")
    expected_criteria = tuple(f"A2-A{number:02d}" for number in range(1, 31))
    actual_criteria = tuple(
        item.criterion_id for item in STATUTORY_ACCEPTANCE_CATALOGUE
    )
    if actual_criteria != expected_criteria:
        raise ValueError("A2 acceptance catalogue is not closed and ordered")
    registry_ids = set(dataset_ids)
    for criterion in STATUTORY_ACCEPTANCE_CATALOGUE:
        unknown = sorted(set(criterion.dataset_ids) - registry_ids)
        if unknown:
            raise ValueError(
                f"A2 acceptance criterion has unknown datasets: {unknown}"
            )


validate_statutory_gate()
