"""Closed design authority for Slice A2 statutory source depth."""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class StatutorySourceDefinition:
    """One required A2 source or produced statutory control dataset."""

    dataset_id: str
    path: str
    owner: str
    record_class: str
    grain: str
    columns: tuple[str, ...]


@dataclass(frozen=True)
class StatutoryAcceptanceCriterion:
    """One blocking A2 acceptance claim."""

    criterion_id: str
    claim: str
    evidence_method: str
    dataset_ids: tuple[str, ...]


