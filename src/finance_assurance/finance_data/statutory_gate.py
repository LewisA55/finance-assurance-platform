def _source(
    dataset_id: str,
    path: str,
    owner: str,
    record_class: str,
    grain: str,
    *columns: str,
) -> StatutorySourceDefinition:
    return StatutorySourceDefinition(
        dataset_id=dataset_id,
        path=path,
        owner=owner,
        record_class=record_class,
        grain=grain,
        columns=columns,
    )


